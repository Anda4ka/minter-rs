const LANG_KEY = "minter_lang";

export function getLang() {
  const v = localStorage.getItem(LANG_KEY);
  return v === "ru" ? "ru" : "en";
}

export function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang === "ru" ? "ru" : "en");
}

export function t(key, vars) {
  const lang = getLang();
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return s;
}

export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    // Don't overwrite dynamic session text on home-last-mint if already has run data
    if (el.id === "home-last-mint" && el.dataset.hasRun === "1") return;
    el.textContent = t(key);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.placeholder = t(key);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) el.title = t(key);
  });
  const langChip = document.getElementById("lang-chip");
  if (langChip) langChip.textContent = getLang().toUpperCase();
  const cancel = document.getElementById("modal-cancel");
  if (cancel) cancel.textContent = t("modal.cancel");
}
